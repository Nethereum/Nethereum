using CodeQuality.Core.Config;
using CodeQuality.Core.Exclusion;
using Xunit;

namespace CodeQuality.Tests.Exclusion;

public class GeneratedFileFilterTests
{
    static GeneratedFileFilter Filter() => new(new GeneratedFileRules
    {
        FileNameSuffixes = { ".gen.cs", ".Designer.cs", "Definition.cs" },
        FileNamePrefixes = { "Rule_" },
        PathSegments = { "Migrations" },
        HeaderMarkers = { "auto-generated" },
        HeaderScanChars = 400,
    });

    [Theory]
    [InlineData("/repo/src/Pkg/HubDefinition.gen.cs")]
    [InlineData("/repo/src/Pkg/WorldDefinition.cs")]
    [InlineData("/repo/src/Pkg/Model.Designer.cs")]
    [InlineData("/repo/src/Pkg/Rule_IPv6address.cs")]
    [InlineData("/repo/src/Pkg/Migrations/InitialCreate.cs")]
    public void ExcludesByPathPattern(string path) =>
        Assert.True(Filter().IsGenerated(path, "class C { }"));

    [Fact]
    public void ExcludesByHeaderMarker() =>
        Assert.True(Filter().IsGenerated("/repo/src/Pkg/Thing.cs", "// <auto-generated />\nclass C { }"));

    [Fact]
    public void IgnoresMarkerBeyondHeaderScanWindow()
    {
        var source = new string(' ', 500) + "// auto-generated";
        Assert.False(Filter().IsGenerated("/repo/src/Pkg/Thing.cs", source));
    }

    [Fact]
    public void KeepsOrdinaryHandWrittenFile() =>
        Assert.False(Filter().IsGenerated("/repo/src/Pkg/SnapSyncClient.cs", "class C { }"));

    [Fact]
    public void EmptyRulesExcludeNothing()
    {
        var filter = new GeneratedFileFilter(new GeneratedFileRules());
        Assert.False(filter.IsGenerated("/repo/x.gen.cs", "// auto-generated"));
    }

    [Fact]
    public void NegativeHeaderScanCharsDegradesToNoHeaderMatch()
    {
        var filter = new GeneratedFileFilter(new GeneratedFileRules
        {
            HeaderMarkers = { "auto-generated" },
            HeaderScanChars = -1,
        });
        Assert.False(filter.IsGenerated("/repo/src/Pkg/Thing.cs", "// <auto-generated />\nclass C { }"));
    }

    [Fact]
    public void ZeroHeaderScanCharsExcludesNothingByHeader()
    {
        var filter = new GeneratedFileFilter(new GeneratedFileRules
        {
            HeaderMarkers = { "auto-generated" },
            HeaderScanChars = 0,
        });
        Assert.False(filter.IsGenerated("/repo/src/Pkg/Thing.cs", "// <auto-generated />\nclass C { }"));
    }

    [Fact]
    public void FileNameSuffixMatchIsCaseInsensitive() =>
        Assert.True(Filter().IsGenerated("/repo/src/Pkg/Thing.GEN.CS", "class C { }"));

    [Fact]
    public void FileNamePrefixMatchIsCaseInsensitive() =>
        Assert.True(Filter().IsGenerated("/repo/src/Pkg/RULE_Thing.cs", "class C { }"));

    [Fact]
    public void PathSegmentMatchIsCaseInsensitive() =>
        Assert.True(Filter().IsGenerated("/repo/src/Pkg/MIGRATIONS/InitialCreate.cs", "class C { }"));

    [Fact]
    public void HeaderMarkerMatchIsCaseInsensitive() =>
        Assert.True(Filter().IsGenerated("/repo/src/Pkg/Thing.cs", "// <AUTO-GENERATED />\nclass C { }"));
}
